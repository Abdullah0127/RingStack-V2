export function seedDevelopmentOffers(db, now = Date.now) {
  const insert = db.prepare(`
    INSERT INTO offers (
      id, title, campaign_type, industry, vertical, product_type, payment_terms,
      payout_method, payout_amount, payout_currency, states_json, schedule,
      percentage, buffer_seconds, available_from, description,
      qualification_requirements, traffic_requirements, restrictions_json,
      status, is_demo, created_at, updated_at
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'active', 1, ?, ?)
    ON CONFLICT(id) DO NOTHING
  `)
  const timestamp = now()
  for (const offer of demoOffers) {
    insert.run(
      offer.id,
      offer.title,
      offer.campaignType,
      offer.industry,
      offer.vertical,
      offer.productType,
      offer.paymentTerms,
      offer.payoutMethod,
      offer.payoutAmount,
      offer.payoutCurrency,
      JSON.stringify(offer.states || sampleStates),
      offer.schedule,
      offer.percentage ?? null,
      offer.bufferSeconds ?? null,
      offer.availableFrom,
      offer.description,
      offer.qualificationRequirements,
      offer.trafficRequirements,
      JSON.stringify(offer.restrictions || []),
      timestamp,
      timestamp,
    )
  }
}
